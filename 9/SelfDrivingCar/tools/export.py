"""Turn trained weights into Jack source.

usage: python3 export.py [WEIGHTS.json] [OUT_DIR]
Writes OUT_DIR/Weights.jack (the 272 network parameters) and OUT_DIR/Tables.jack (sine table).
Defaults: tools/champion.json  ->  the Jack program folder (the parent of tools/).
Both files are GENERATED: never edit them by hand, re-run this script instead.
"""
import sys, os, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sim


def lets(name, vals):
    return "\n".join("        let %s[%d] = %d;" % (name, i, v) for i, v in enumerate(vals))


def check(net):
    assert len(net) == sim.N_PARAMS, "expected %d parameters, got %d" % (sim.N_PARAMS, len(net))
    p = 0
    for li in range(3):
        for _ in range(sim.SIZES[li + 1]):
            assert -sim.B_MAX <= net[p] <= sim.B_MAX, "bias out of range at %d" % p
            p += 1
            for _ in range(sim.SIZES[li]):
                assert -sim.W_MAX <= net[p] <= sim.W_MAX, "weight out of range at %d" % p
                p += 1


def weights_jack(net):
    return ("// GENERATED by tools/export.py - do not edit.\n"
            "/** The trained network: 272 integers. Per neuron: [bias, w0, w1, ...]. */\n"
            "class Weights {\n    function void fill(Array w) {\n%s\n        return;\n    }\n}\n" % lets("w", net))


def tables_jack():
    return """// GENERATED by tools/export.py - do not edit.
/** sin and cos for angles 0..719 (half degrees), scaled by 128. */
class Tables {
    static Array sin, cos;

    function Array getSin() { return sin; }
    function Array getCos() { return cos; }

    function void init() {
        var Array q;
        var int a, b, v;
        let q = Array.new(181);
%s
        let sin = Array.new(720);
        let cos = Array.new(720);
        let a = 0;
        while (a < 720) {
            let b = a;
            if (b > 359) { let b = b - 360; }
            if (b > 180) { let b = 360 - b; }
            let v = q[b];
            if (a > 359) { let v = -v; }
            let sin[a] = v;
            let a = a + 1;
        }
        let a = 0;
        while (a < 720) {
            let b = a + 180;
            if (b > 719) { let b = b - 720; }
            let cos[a] = sin[b];
            let a = a + 1;
        }
        do q.dispose();
        return;
    }
}
""" % lets("q", sim.QSIN)


def export(net, out_dir):
    check(net)
    open(os.path.join(out_dir, "Weights.jack"), "w").write(weights_jack(net))
    open(os.path.join(out_dir, "Tables.jack"), "w").write(tables_jack())


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "champion.json")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(HERE)
    net = json.load(open(src))
    export(net, out)
    print("wrote Weights.jack and Tables.jack to", out)
    print("largest layer sums this network can reach:", sim.worst_case_sums(net), "(limit 32767)")
